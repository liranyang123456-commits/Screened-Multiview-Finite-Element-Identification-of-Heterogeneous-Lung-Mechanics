def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _load_gnn(checkpoint: Path) -> tuple[torch.nn.Module, dict]:
    state = torch.load(checkpoint, map_location="cpu", weights_only=True)
    config = state["config"]
    model = build_model(
        config["model"],
        config["input_dim"],
        config["hidden_dim"],
        config["layers"],
        config["dropout"],
        config.get("dynamic_dim"),
    )
    model.load_state_dict(state["model"])
    model.eval()
    return model, config


# --------------------------------------------------------------------------
# Observation regeneration: call the audit scripts' own _reproject and capture
# the deformed depth produced by the very same project() call.
# --------------------------------------------------------------------------
class _DepthRecorder:
    def __init__(self) -> None:
        self.depths: list[torch.Tensor] = []

    def __call__(self, points, c2w, focal, H, W):
        uv, depth, valid = project(points, c2w, focal=focal, H=H, W=W)
        self.depths.append(depth.detach().clone())
        return uv, depth, valid


def regenerate(scene: dict, experiments: list[dict], condition: str) -> dict:
    module = audit_constitutive if condition in ("fiber", "viscous") else audit_structural
    recorder = _DepthRecorder()
    original = module.project
    module.project = recorder
    try:
        reprojected = module._reproject(scene, experiments, condition)
    finally:
        module.project = original
    gap = reprojected.get("peak_displacement_relative_gap", reprojected.get("peak_gap"))
    uv_only = reprojected["experiments"]
    uv_depth = []
    cursor = 0
    for source, replaced in zip(experiments, uv_only, strict=True):
        frames, views = source["image_uv_deformed_multiview_seq"].shape[:2]
        depth = source["image_depth_deformed_multiview_seq"].to(torch.float64).clone()
        for frame in range(frames):
            if module is audit_structural and float(source["forces"][frame].abs().max()) == 0.0:
                continue  # audit_structural skips zero-force frames (tracks left as stored)
            for view in range(views):
                depth[frame, view] = recorder.depths[cursor].to(depth.dtype)
                cursor += 1
        fields = dict(replaced)
        fields["image_depth_deformed_multiview_seq"] = depth
        uv_depth.append(fields)
    if cursor != len(recorder.depths):
        raise RuntimeError(f"depth capture mismatch: used {cursor} of {len(recorder.depths)}")
    return {"uv_only": uv_only, "uv_depth": uv_depth, "peak_displacement_relative_gap": float(gap)}


# --------------------------------------------------------------------------
# In-memory graph construction through the production graph builder.
# --------------------------------------------------------------------------
@contextlib.contextmanager
def _in_memory_experiments(row: dict, experiments: list[dict]):
    mapping = {
        str((CT_DATASET / item["relative_path"]).resolve()): experiment
        for item, experiment in zip(row["experiments"], experiments, strict=True)
    }
    real_load = torch.load

    def patched_load(path, *args, **kwargs):
        key = str(Path(path).resolve())
        if key in mapping:
            return mapping[key]
        return real_load(path, *args, **kwargs)

    torch.load = patched_load
    try:
        yield
    finally:
        torch.load = real_load


class LearnedInitializer:
    def __init__(self) -> None:
        self.selected_model, self.selected_config = _load_gnn(SELECTED_GNN)
        self.ratio_model, self.ratio_config = _load_gnn(SEED_2028_GNN)
        self.artifact = joblib.load(BASELINE_ARTIFACT)
        if self.artifact.get("schema_version") != 4:
            raise ValueError("Unsupported baseline artifact schema")
        # Same constructor defaults as benchmark_ion_ct_synthetic_mechanics.external_dataset.
        self.dataset = SimLungGraphDataset(CT_DATASET, split=None)
        self.device = torch.device("cpu")

    def graph(self, row: dict, experiments: list[dict]) -> dict:
        self.dataset.patients = [row]
        with _in_memory_experiments(row, experiments):
            graph = self.dataset[0]
        if int(graph["x"].shape[1]) != int(self.selected_config["input_dim"]):
            raise RuntimeError("input_dim mismatch with checkpoint")
        if int(graph["dynamic_seq"].shape[-1]) != int(self.selected_config["dynamic_dim"]):
            raise RuntimeError("dynamic_dim mismatch with checkpoint")
        return graph

    def predict(self, row: dict, experiments: list[dict]) -> dict:
        graph = self.graph(row, experiments)
        _, selected_rows = evaluate(
            self.selected_model,
            [[graph]],
            self.device,
            geometry_fusion_weight=float(self.selected_config.get("geometry_fusion_weight", 0.5)),
        )
        _, ratio_rows = evaluate(
            self.ratio_model,
            [[graph]],
            self.device,
            geometry_fusion_weight=float(self.ratio_config.get("geometry_fusion_weight", 0.5)),
        )
        selected = selected_rows[0]
        ratio_2028 = ratio_rows[0]
        X = features(graph)[None, :]
        X_model = guarded_features(X, self.artifact)
        estimators = self.artifact["models"]["pca_ridge"]
        prediction = _prediction(estimators["main"], X_model)
        prediction[:, 5] = _prediction(estimators["radius"], X_model).reshape(-1)
        prediction = guarded_prediction(prediction, self.artifact)
        ood_score = float(feature_ood_scores(X, self.artifact)[0])
        ood_threshold = float(self.artifact["train_support_guard"]["ood_score_threshold"])
        label = graph["labels"]
        raw_hybrid = float(selected["inclusion_ratio_estimated"])
        raw_2028 = float(ratio_2028["inclusion_ratio_estimated"])
        return {
            "truth": {
                "E_background": float(math.exp(float(label["log_E_background"]))),
                "inclusion_ratio": float(math.exp(float(label["log_ratio"]))),
                "center_fraction": [float(v) for v in label["center_fraction"].tolist()],
                "radius_fraction": float(label["radius_fraction"]),
                "heterogeneous": bool(float(label["heterogeneous"]) > 0.5),
            },
            "E_background_estimated": float(selected["E_background_estimated"]),
            "log_E_std": float(selected["log_E_std"]),
            "inclusion_ratio_raw_hybrid": raw_hybrid,
            "inclusion_ratio_raw_2028": raw_2028,
            "inclusion_ratio_official": float(official_bins3_regularized(raw_2028)),
            "inclusion_ratio_bins3_of_hybrid_raw": float(official_bins3_regularized(raw_hybrid)),
            "log_ratio_std_2028": float(ratio_2028["log_ratio_std"]),
            "heterogeneity_probability_hybrid": float(selected["heterogeneity_probability"]),
            "heterogeneity_probability_2028": float(ratio_2028["heterogeneity_probability"]),
            "center_fraction_estimated": [float(v) for v in selected["center_fraction_estimated"]],
            "radius_fraction_estimated": float(prediction[0, 5]),
            "radius_fraction_mesh_gnn": float(selected["radius_fraction_estimated"]),
            "pca_ridge_E_background_estimated": float(math.exp(float(prediction[0, 0]))),
            "pca_ridge_inclusion_ratio_estimated": float(math.exp(float(prediction[0, 1]))),
            "pca_ridge_ood_score": ood_score,
            "pca_ridge_ood_detected": bool(ood_score > ood_threshold),
        }


# --------------------------------------------------------------------------
# Metrics
# --------------------------------------------------------------------------
def _rel(estimate: float, truth: float) -> float:
    return abs(float(estimate) / float(truth) - 1.0)


def _errors(prediction: dict) -> dict:
    truth = prediction["truth"]
    center_est = np.asarray(prediction["center_fraction_estimated"], dtype=float)
    center_true = np.asarray(truth["center_fraction"], dtype=float)
    return {
        "E_background_relative_error": _rel(prediction["E_background_estimated"], truth["E_background"]),
        "inclusion_ratio_raw_hybrid_relative_error": _rel(prediction["inclusion_ratio_raw_hybrid"], truth["inclusion_ratio"]),
        "inclusion_ratio_raw_2028_relative_error": _rel(prediction["inclusion_ratio_raw_2028"], truth["inclusion_ratio"]),
        "inclusion_ratio_official_relative_error": _rel(prediction["inclusion_ratio_official"], truth["inclusion_ratio"]),
        "center_error_normalized": float(np.linalg.norm(center_est - center_true)) if truth["heterogeneous"] else None,
        "radius_relative_error": _rel(prediction["radius_fraction_estimated"], truth["radius_fraction"]) if truth["heterogeneous"] else None,
    }


def _deltas(prediction: dict, matched: dict) -> dict:
    center = np.asarray(prediction["center_fraction_estimated"], dtype=float)
    center_matched = np.asarray(matched["center_fraction_estimated"], dtype=float)
    return {
        "E_background_log_delta": math.log(prediction["E_background_estimated"] / matched["E_background_estimated"]),
        "E_background_relative_change": prediction["E_background_estimated"] / matched["E_background_estimated"] - 1.0,
        "inclusion_ratio_raw_hybrid_log_delta": math.log(prediction["inclusion_ratio_raw_hybrid"] / matched["inclusion_ratio_raw_hybrid"]),
        "inclusion_ratio_raw_2028_log_delta": math.log(prediction["inclusion_ratio_raw_2028"] / matched["inclusion_ratio_raw_2028"]),
        "inclusion_ratio_official_log_delta": math.log(prediction["inclusion_ratio_official"] / matched["inclusion_ratio_official"]),
        "inclusion_ratio_official_relative_change": prediction["inclusion_ratio_official"] / matched["inclusion_ratio_official"] - 1.0,
        "center_shift_normalized": float(np.linalg.norm(center - center_matched)),
        "radius_relative_change": prediction["radius_fraction_estimated"] / matched["radius_fraction_estimated"] - 1.0,
        "heterogeneity_probability_hybrid_delta": prediction["heterogeneity_probability_hybrid"] - matched["heterogeneity_probability_hybrid"],
    }


def _reproduction_check(patient_id: str, prediction: dict, stored_hybrid: dict, stored_official: dict, stored_2028_raw: float) -> dict:
    """Compare matched re-inference with the frozen stored predictions."""
    pairs = {
        "E_background_estimated": (prediction["E_background_estimated"], float(stored_hybrid["E_background_estimated"])),
        "inclusion_ratio_raw_hybrid": (prediction["inclusion_ratio_raw_hybrid"], float(stored_hybrid["inclusion_ratio_estimated"])),
        "log_E_std": (prediction["log_E_std"], float(stored_hybrid["log_E_std"])),
        "radius_fraction_estimated": (prediction["radius_fraction_estimated"], float(stored_hybrid["radius_fraction_estimated"])),
        "inclusion_ratio_raw_2028": (prediction["inclusion_ratio_raw_2028"], float(stored_2028_raw)),
        "inclusion_ratio_official": (prediction["inclusion_ratio_official"], float(stored_official["inclusion_ratio_estimated"])),
    }
    for axis, (ours, theirs) in enumerate(zip(prediction["center_fraction_estimated"], stored_hybrid["center_fraction_estimated"])):
        pairs[f"center_fraction_{'xyz'[axis]}"] = (float(ours), float(theirs))
    deviations = {}
    worst_abs = 0.0
    worst_rel = 0.0
    for key, (ours, theirs) in pairs.items():
        absolute = abs(ours - theirs)
        relative = absolute / max(abs(theirs), 1e-12)
        deviations[key] = {"reinferred": ours, "stored": theirs, "abs": absolute, "rel": relative}
        worst_abs = max(worst_abs, absolute)
        worst_rel = max(worst_rel, relative)
    return {
        "patient_id": patient_id,
        "max_abs_deviation": worst_abs,
        "max_rel_deviation": worst_rel,
        "within_tolerance": worst_rel <= REPRODUCTION_TOLERANCE,
        "per_field": deviations,
    }


def _load_audit_gaps() -> dict[str, dict[str, float]]:
    gaps: dict[str, dict[str, float]] = {}
    for condition, path in AUDIT_RECORDS.items():
        if not path.exists():
            continue
        gaps[condition] = {}
        for line in path.read_text(encoding="utf-8").splitlines():
            if line.strip():
                row = json.loads(line)
                gaps[condition][row["patient_id"]] = float(row["peak_displacement_relative_gap"])
    return gaps


