def _median_iqr(values: list[float]) -> dict:
    array = np.asarray([v for v in values if v is not None and np.isfinite(v)], dtype=float)
    if array.size == 0:
        return {"n": 0, "median": None, "q1": None, "q3": None}
    q1, median, q3 = np.quantile(array, (0.25, 0.5, 0.75))
    return {
        "n": int(array.size),
        "median": float(median),
        "q1": float(q1),
        "q3": float(q3),
        "min": float(array.min()),
        "max": float(array.max()),
    }


