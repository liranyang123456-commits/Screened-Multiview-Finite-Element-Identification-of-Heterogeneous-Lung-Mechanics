def run_shard(shard: int, shard_count: int, scratch: Path) -> None:
    patient_ids = json.loads(IDS.read_text(encoding="utf-8"))
    mine = patient_ids[shard::shard_count]
    manifest = json.loads((CT_DATASET / "manifest.json").read_text(encoding="utf-8"))
    rows = {row["patient_id"]: row for row in manifest["patients"]}
    stored_hybrid = _index_records(CT_HYBRID, method="ours_hybrid_initializer")
    stored_official = _official_2028_ratio_index()
    stored_2028_raw = {
        _normalize_id(str(row["patient_id"])): float(row["inclusion_ratio_estimated"])
        for row in json.loads(CT_GNN_2028.read_text(encoding="utf-8"))["records"]
    }
    audit_gaps = _load_audit_gaps()
    initializer = LearnedInitializer()
    scratch.mkdir(parents=True, exist_ok=True)
    out_path = scratch / f"records_shard{shard}.jsonl"
    check_path = scratch / f"reproduction_shard{shard}.json"
    checks = []
    with out_path.open("w", encoding="utf-8") as handle:
        for patient_id in mine:
            row = rows[patient_id]
            scene, experiments = load_patient(CT_DATASET, row)
            started = time.time()
            matched = initializer.predict(row, experiments)
            key = _normalize_id(patient_id)
            check = _reproduction_check(
                patient_id,
                matched,
                stored_hybrid[key],
                stored_official.get(_official_ratio_key(row)) or stored_official[key],
                stored_2028_raw[key],
            )
            checks.append(check)
            check_path.write_text(json.dumps(checks, indent=2), encoding="utf-8")
            print(
                f"[{patient_id}] matched reproduction max_rel_dev={check['max_rel_deviation']:.2e} "
                f"max_abs_dev={check['max_abs_deviation']:.2e} ok={check['within_tolerance']}",
                flush=True,
            )
            if not check["within_tolerance"]:
                print("REPRODUCTION FAILED; stopping shard", flush=True)
                return
            base = {
                "patient_id": patient_id,
                "geometry_id": row.get("geometry_id"),
                "scenario_id": row.get("scenario_id"),
            }
            handle.write(
                json.dumps(
                    {
                        **base,
                        "condition": "matched",
                        "variant": "stored",
                        "peak_displacement_relative_gap": 0.0,
                        **{k: v for k, v in matched.items()},
                        **_errors(matched),
                        **{k: 0.0 for k in _deltas(matched, matched)},
                    }
                )
                + "\n"
            )
            handle.flush()
            matched_E_error = _errors(matched)["E_background_relative_error"]
            for condition in CONDITIONS:
                t0 = time.time()
                regenerated = regenerate(scene, experiments, condition)
                audit_gap = audit_gaps.get(condition, {}).get(patient_id)
                for variant in VARIANTS:
                    prediction = initializer.predict(row, regenerated[variant])
                    record = {
                        **base,
                        "condition": condition,
                        "variant": variant,
                        "peak_displacement_relative_gap": regenerated["peak_displacement_relative_gap"],
                        "audit_peak_displacement_relative_gap": audit_gap,
                        **prediction,
                        **_errors(prediction),
                        **_deltas(prediction, matched),
                    }
                    handle.write(json.dumps(record) + "\n")
                    handle.flush()
                    if variant == "uv_depth":
                        print(
                            f"  {condition:15s} gap={regenerated['peak_displacement_relative_gap']:.4f} "
                            f"E_err={record['E_background_relative_error']:.3f} "
                            f"(matched {matched_E_error:.3f}) "
                            f"ratio_off_err={record['inclusion_ratio_official_relative_error']:.3f} "
                            f"dE={record['E_background_relative_change']:+.3f} "
                            f"dc={record['center_shift_normalized']:.3f} "
                            f"dr={record['radius_relative_change']:+.3f} "
                            f"t={time.time() - t0:.0f}s",
                            flush=True,
                        )
            print(f"[{patient_id}] done in {time.time() - started:.0f}s", flush=True)


